"""Write docs/paper/appendix/k-prompts.tex: one real model exchange per generative stage.

For each stage, takes the first successful call of the latest run directory that has that stage
(data/<series>/_runs/*/calls.jsonl) and prints the system prompt, the user prompt and the raw
response exactly as logged, with long fields elided in the middle (the elision says how many
characters were left out). Non-ASCII typography is folded to ASCII so pdfLaTeX can set it.
No model call. Run: python scripts/papers/prompt_appendix.py
"""
import json
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "paper" / "appendix" / "k-prompts.tex"
# (stage, series dir, title, what the stage does)
STAGES = [
    ("entity_classify", "anne", "Entity typing", "types each mined name candidate (\\sys, gazetteer)"),
    ("entity_alias", "anne", "Alias adjudication", "decides whether two surface forms are one entity (\\sys, gazetteer)"),
    ("claim_extract", "anne", "Claim extraction", "extracts dated, quoted claims about one character from one evidence window (\\sys)"),
    ("scene_extract", "anne", "Scene extraction", "records scenes, participants and events over a chapter span (\\sys)"),
    ("infobox_extract", "anne", "Infobox pass", "long-context pass for gender, age and origin (\\sys)"),
    ("backstory_extract", "anne", "Backstory pass", "long-context pass for background facts (\\sys)"),
    ("arbitrate", "anne", "Arbitration", "resolves a same-volume conflict between two values (\\sys)"),
    ("verify", "anne", "Verification", "checks stored facts against their own cited evidence (\\sys)"),
    ("prose", "anne", "Page prose", "writes background/personality prose from the cutoff-filtered claims (\\sys)"),
    ("codex_summary", "anne", "Codex summary", "writes the one-sentence summary of a shared codex entry (\\sys)"),
    ("baseline_page", "anne@b1", "B1 page", "long-context baseline: one character page from the whole prefix"),
    ("baseline_page", "anne@b2", "B2 page", "prefix-retrieval baseline: one character page from retrieved passages"),
    ("baseline_lightrag", "anne@b3", "B3 index (LightRAG)", "LightRAG's own entity and relation extraction while building its index"),
    ("baseline_page", "anne@b3", "B3 page", "LightRAG baseline: one character page from LightRAG context"),
    ("baseline_page", "anne@x1", "X1 page", "closed-book diagnostic: title and character name only"),
    ("baseline_page", "anne@x2", "X2 page", "instructed full-text diagnostic: all five volumes and the cutoff instruction"),
    ("decon_paraphrase", "anne-decon", "Decontamination paraphrase", "paraphrases one renamed paragraph"),
    ("probe_memorization", "anne-decon", "Memorization probe", "name cloze / title identification on one paragraph"),
]
CAPS = {"system": (2200, 600), "prompt": (1800, 600), "response": (1800, 500)}
FOLD = {"\u201c": '"', "\u201d": '"', "\u2018": "'", "\u2019": "'", "\u2014": "--", "\u2013": "-",
        "\u2026": "...", "\u00a0": " ", "\u2192": "->", "\u2264": "<=", "\u2265": ">="}


def ascii_fold(s: str) -> str:
    s = "".join(FOLD.get(ch, ch) for ch in s)
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode("ascii")
    return s.replace("\t", "    ")


def elide(s: str, head: int, tail: int) -> str:
    if len(s) <= head + tail + 200:
        return s
    return s[:head] + f"\n[... {len(s) - head - tail:,} characters elided ...]\n" + s[-tail:]


def pick(stage: str, series: str) -> tuple[dict, str] | None:
    for f in sorted((ROOT / "data" / series / "_runs").glob("*/calls.jsonl"), reverse=True):
        for line in f.open(encoding="utf-8"):
            r = json.loads(line)
            if r.get("stage") == stage and not r.get("error") and r.get("response"):
                return r, f.parent.name
    return None


def block(label: str, text: str) -> str:
    return (f"\\noindent\\textit{{{label}}}\n\\begin{{lstlisting}}\n{text}\n\\end{{lstlisting}}\n")


def main() -> None:
    parts = [
        "% Generated by scripts/papers/prompt_appendix.py from data/*/_runs/*/calls.jsonl. Do not edit.",
        "\\section{Prompts and Model Exchanges}",
        "\\label{app:prompts}",
        "Every generative step of every system goes through one client that logs the system prompt, "
        "the user prompt and the raw response of each call. For each stage below we reproduce one "
        "logged call verbatim: the first successful call of the latest run of that stage behind the "
        "reported cells. Long fields are cut in the middle, and the cut states how many characters it "
        "removed; typographic characters are folded to ASCII for typesetting. Every call shown was "
        "answered by \\res{GEN-model}. The complete prompts and every logged call are in the release "
        "(Appendix~\\ref{app:reproducibility}). Annotation was not done through this client: the LLM "
        "annotators worked from the written rules of Appendix~\\ref{app:annotation}.",
        "",
    ]
    for stage, series, title, what in STAGES:
        got = pick(stage, series)
        if not got:
            continue
        r, run = got
        parts.append(f"\\subsection*{{{title}}}")
        tt = lambda s: "\\texttt{" + ascii_fold(s).replace("_", "\\_") + "}"
        parts.append(f"{what[0].upper() + what[1:]}. Model {tt(r.get('model', ''))}; "
                     f"{r.get('in_tokens', 0):,} input and {r.get('out_tokens', 0):,} output tokens; "
                     f"run \\nolinkurl{{{ascii_fold(series + '/' + run)}}}.\n")
        for field, label in (("system", "System prompt"), ("prompt", "User prompt (input)"), ("response", "Model output")):
            text = r.get(field) or ""
            if not text.strip():
                continue
            parts.append(block(label, ascii_fold(elide(text, *CAPS[field]))))
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
