"""Reanalyse stored NarrativeWiki labels for paper_codex; no model calls or label edits.

Run from the repository root:
  .venv/Scripts/python.exe -X utf8 scripts/papers/codex_paper_analysis.py

Outputs: paper_codex/analysis/reanalysis.json, README.md, and tables/t-*.tex.
Every input read is hashed. Means are unweighted means of cutoff-specific ratios;
pooled counts are explicitly distinct. Neither provides an independent-corpus
estimate. The accepted review is author acceptance of an AI draft, not independent
human annotation. The evidence-packet subset is a post-hoc sensitivity analysis.
"""

from __future__ import annotations

import csv
import hashlib
import io
import json
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
EV = ROOT / "docs" / "eval"
OUT = ROOT / "paper_codex"
sys.path.insert(0, str(ROOT / "src"))
from narrativewiki.entities.gazetteer import slugify  # noqa: E402

SYSTEMS = {"B1": "b1", "B2": "b2", "B3": "b3", "B4": "b4-v2",
           "B5": "v2", "X1": "x1", "X2": "x2"}
NAMES = {"B1": "Long context", "B2": "Prefix retrieval", "B3": "LightRAG",
         "B4": "Graph retrieval", "B5": "NarrativeWiki", "X1": "Closed book", "X2": "Full text"}
INPUTS: dict[str, str] = {}


def read(path: Path) -> str:
    raw = path.read_bytes()
    INPUTS[path.relative_to(ROOT).as_posix()] = hashlib.sha256(raw).hexdigest()
    return raw.decode("utf-8-sig")


def js(path: Path):
    return json.loads(read(path))


def jl(path: Path):
    return [json.loads(line) for line in read(path).splitlines() if line.strip()]


def fraction(n: int, d: int) -> dict:
    return {"num": n, "den": d, "rate": n / d if d else None}


def summarize(cells: list[dict]) -> dict:
    values = [c["num"] / c["den"] for c in cells if c["den"]]
    return {"cells": cells, "mean_over_cutoffs": statistics.mean(values) if values else None,
            "pooled": fraction(sum(c["num"] for c in cells), sum(c["den"] for c in cells))}


def tex_table(path: str, columns: str, header: str, rows: list[str], caption: str, label: str,
              wide: bool = False):
    environment = "table*" if wide else "table"
    text = ["% Generated by scripts/papers/codex_paper_analysis.py; do not edit.",
            f"\\begin{{{environment}}}[t]", "\\centering\\small",
            "\\setlength{\\tabcolsep}{3pt}", f"\\begin{{tabular}}{{@{{}}{columns}@{{}}}}",
            "\\toprule", header + r" \\", "\\midrule", *rows,
            "\\bottomrule", "\\end{tabular}", f"\\caption{{{caption}}}",
            f"\\label{{{label}}}", f"\\end{{{environment}}}", ""]
    (OUT / "tables" / path).write_text("\n".join(text), encoding="utf-8", newline="\n")


def count_tex(c: dict, field: str) -> str:
    return f"{c[field]}/{c['n']}"


def main():
    for subdir in ("analysis", "tables"):
        (OUT / subdir).mkdir(parents=True, exist_ok=True)
    read(Path(__file__).resolve())
    read(ROOT / "src" / "narrativewiki" / "entities" / "gazetteer.py")
    review_key = js(EV / "human_check" / "key.json")
    accepted = list(csv.DictReader(io.StringIO(read(EV / "human_check" / "final_labels.csv"))))
    assert len(accepted) == len(review_key) == 554
    assert len({r["item"] for r in accepted}) == 554
    audited_gold = {f"C {review_key[r['item']]['character']} | {review_key[r['item']]['claim']}":
                    r["accepted label"] for r in accepted if r["item"].startswith("G")}
    assert Counter(audited_gold.values()) == {"yes": 85, "partly": 23, "no": 3}
    reliable_packet = {key for key, answer in audited_gold.items() if answer == "yes"}
    pair = js(EV / "precision" / "pair_strict_claude.json")
    timeline = js(EV / "precision" / "timeline_cite_claude.json")

    # Official observation cells retain the original label populations and pair/citation sidecars.
    cells = {}
    recalls = {}
    sensitivity = {}
    surfaces = {}
    sample_rows = {}
    for condition, prefix in (("original", "anne"), ("treated", "anne-decon")):
        cells[condition], recalls[condition], sensitivity[condition] = {}, {}, {}
        for system, tag in SYSTEMS.items():
            series = f"{prefix}@{tag}"
            agg = defaultdict(lambda: [0, 0])
            for row in jl(EV / "observations" / f"{series}_{system}.jsonl"):
                assert row["system"] == system
                agg[row["metric"], row["cutoff"]][0] += row["num"]
                agg[row["metric"], row["cutoff"]][1] += row["den"]
            cells[condition][system] = {}
            for metric in ("M1", "M3", "M8", "M4"):
                cc = [{"cutoff": t, **fraction(*agg[metric, t])} for t in range(1, 6)
                      if agg[metric, t][1]]
                cells[condition][system][metric] = summarize(cc)
            recalls[condition][system] = {}
            subset = []
            for cutoff in range(1, 6):
                recall = js(EV / "recall_hand" / f"{series}_v{cutoff}.json")
                assert set(recall) <= set(audited_gold), (series, cutoff, set(recall) - set(audited_gold))
                assert all(v in {"yes", "no"} for v in recall.values()), (series, cutoff)
                original = agg["M1", cutoff]
                assert original == [sum(v == "yes" for v in recall.values()), len(recall)]
                recalls[condition][system][cutoff] = recall
                selected = {k: v for k, v in recall.items() if k in reliable_packet}
                subset.append({"cutoff": cutoff,
                               **fraction(sum(v == "yes" for v in selected.values()), len(selected))})
            sensitivity[condition][system] = summarize(subset)

    # Paired here means identical selected-gold assessments, including facts on missing pages.
    paired = {}
    for condition in cells:
        paired[condition] = {}
        for comparator in SYSTEMS:
            if comparator == "B5":
                continue
            pp = []
            for t in range(1, 6):
                a, b = recalls[condition]["B5"][t], recalls[condition][comparator][t]
                assert set(a) == set(b), (condition, comparator, t)
                counts = Counter((a[k] == "yes", b[k] == "yes") for k in a)
                pp.append({"cutoff": t, "den": len(a), "both": counts[True, True],
                           "neither": counts[False, False], "nw_only": counts[True, False],
                           "comparator_only": counts[False, True],
                           "difference": (counts[True, False] - counts[False, True]) / len(a)})
            paired[condition][comparator] = {
                "cells": pp, "mean_difference_over_cutoffs": statistics.mean(p["difference"] for p in pp),
                **{k: sum(p[k] for p in pp) for k in ("den", "both", "neither", "nw_only", "comparator_only")}}

    # Page strata from the existing registry's gold characters and canonical page maps.
    for system, tag in SYSTEMS.items():
        series = f"anne@{tag}"
        gold = yaml.safe_load(read(EV / "parametric" / "anne.yaml"))["characters"]
        pmap_path = EV / "parametric" / "pages" / f"{series}.yaml"
        pmap = yaml.safe_load(read(pmap_path)) or {} if pmap_path.exists() else {}
        cast = set()
        for name in gold:
            slugs = pmap.get(name) or [slugify(name)]
            cast.update(f"character/{s}.md" for s in ([slugs] if isinstance(slugs, str) else slugs))

        def page_kind(page):
            top = page.split("/")[0]
            if top == "character":
                return "cast" if page in cast else "other_character"
            return {"relationships": "relationship", "codex": "codex", "timeline": "timeline"}.get(top, "index")

        acc = defaultdict(Counter)
        inventory_share = defaultdict(list)
        for t in range(1, 6):
            inventory = Counter(page_kind(r["page"]) for r in jl(EV / "inventory" / f"{series}_v{t}.jsonl"))
            for kind in ("cast", "other_character", "relationship", "codex", "timeline", "index"):
                inventory_share[kind].append(inventory[kind] / sum(inventory.values()))
            rows = jl(EV / "precision" / f"{series}_v{t}_all.jsonl")
            sample_rows[series, t] = rows
            for index, row in enumerate(rows):
                if (row.get("human") or "") in {"", "frame_error"}:
                    continue
                statement = (row.get("human_atom") or row["human"]) == "supported"
                pair_verdict = pair.get(series, {}).get(str(t), {}).get(str(index))
                page = (statement and pair_verdict["scene"] == "yes") if pair_verdict else row["human"] == "supported"
                cite = (timeline.get(series, {}).get(str(t), {}).get(str(index)) or row).get("cite") or ""
                values = {"n": 1, "statement_supported": int(statement), "page_supported": int(page),
                          "citation_sufficient": int(cite == "sufficient"),
                          "citation_labelled": int(bool(cite)), "cited": int(cite not in {"", "none"})}
                acc["all"].update(values)
                acc[page_kind(row["page"])].update(values)
        surfaces[system] = {kind: {**dict(counts),
                                  "inventory_share_mean_over_cutoffs":
                                  statistics.mean(inventory_share[kind]) if kind != "all" else 1.0}
                            for kind, counts in sorted(acc.items())}
        assert acc["all"]["page_supported"] == cells["original"][system]["M3"]["pooled"]["num"]

    # Keep accepted-review draft agreement separate from current population labels.
    review = {}
    for part in ("G", "R", "P", "C"):
        review[part] = {}
        rr = [r for r in accepted if r["item"].startswith(part)]
        for system in sorted({review_key[r["item"]].get("system", "gold") for r in rr}):
            rows = [r for r in rr if review_key[r["item"]].get("system", "gold") == system]
            transitions = Counter((r["earlier AI label"], r["accepted label"]) for r in rows)
            entry = {"n": len(rows), "accepted_labels": dict(Counter(r["accepted label"] for r in rows)),
                     "earlier_labels": dict(Counter(r["earlier AI label"] for r in rows)),
                     "transitions": [{"earlier": a, "accepted": b, "n": n}
                                     for (a, b), n in sorted(transitions.items())],
                     "exact_draft_agreement": sum(r["earlier AI label"] == r["accepted label"] for r in rows)}
            if part == "P":
                entry["accepted_page_supported"] = sum(r["accepted label"] == "yes" and r["pair"] != "no" for r in rows)
                entry["not_shown"] = sum(r["accepted label"] == "not shown" for r in rows)
                entry["pair_labels"] = dict(Counter(r["pair"] for r in rows))
            if part in {"P", "C"}:
                current = []
                for r in rows:
                    k = review_key[r["item"]]
                    series, t, index = k["series"], k["t"], k["row"]
                    if (series, t) not in sample_rows:
                        sample_rows[series, t] = jl(EV / "precision" / f"{series}_v{t}_all.jsonl")
                    row = sample_rows[series, t][index]
                    atom = (row.get("human_atom") or row.get("human")) == "supported"
                    pv = pair.get(series, {}).get(str(t), {}).get(str(index))
                    page = (atom and pv["scene"] == "yes") if pv else row.get("human") == "supported"
                    cite = (timeline.get(series, {}).get(str(t), {}).get(str(index)) or row).get("cite")
                    current.append({"item": r["item"], "series": series, "cutoff": t, "row": index,
                                    "current_statement_supported": atom, "current_page_supported": page,
                                    "current_citation_label": cite,
                                    "current_population_eligible": row.get("human") not in {None, "", "frame_error"},
                                    "accepted_label": r["accepted label"], "accepted_pair": r["pair"]})
                entry["current_item_labels"] = current
                entry["current_statement_supported_count"] = sum(r["current_statement_supported"] for r in current)
                entry["current_page_supported_count"] = sum(r["current_page_supported"] for r in current)
                entry["current_citation_sufficient_count"] = sum(r["current_citation_label"] == "sufficient" for r in current)
            if part == "R":
                entry["current_recall_agreement"] = sum(
                    recalls["original"][system][review_key[r["item"]]["t"]][review_key[r["item"]]["fact"]]
                    == r["accepted label"] for r in rows)
            review[part][system] = entry

    signature = hashlib.sha256(json.dumps(INPUTS, sort_keys=True).encode()).hexdigest()[:12]
    runid = f"codex-paper-existing-labels-2026-10-09-{signature}"
    result = {"run_id": runid, "source_sha256": dict(sorted(INPUTS.items())),
              "estimands": {"means": "Unweighted mean of per-cutoff proportions, not a corpus population estimate.",
                            "paired": "Same eligible gold fact/cutoff units, including absent pages; not shared output pages.",
                            "review": "Author acceptance of an AI draft; descriptive draft agreement, not annotator IAA.",
                            "sensitivity": "Post-hoc subset of 85 facts with fully established reviewed evidence packets; original reveal-volume labels retained."},
              "gold_review": dict(Counter(audited_gold.values())), "cells": cells,
              "gold_support_sensitivity": sensitivity, "paired_recall": paired,
              "original_surface_samples": surfaces, "accepted_review": review}
    (OUT / "analysis" / "reanalysis.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n",
                                                       encoding="utf-8", newline="\n")

    audit_rows, draft_rows = [], []
    for system in SYSTEMS:
        p = review["P"][system]
        c = review["C"].get(system)
        ptext = f"{p['current_page_supported_count']} $\\to$ {p['accepted_page_supported']}"
        if c:
            eligible = [r for r in c["current_item_labels"] if r["current_population_eligible"]]
            ctext = (f"{sum(r['current_citation_label'] == 'sufficient' for r in eligible)} $\\to$ "
                     f"{sum(r['accepted_label'] == 'yes' for r in eligible)} ({len(eligible)})")
        else:
            ctext = "--"
        audit_rows.append(f"{system} & {ptext} & {p['not_shown']} & {ctext} " + r"\\")
        pdraft = f"{p['earlier_labels'].get('yes', 0)} $\\to$ {p['accepted_labels'].get('yes', 0)}"
        cdraft = f"{c['earlier_labels'].get('yes', 0)} $\\to$ {c['accepted_labels'].get('yes', 0)}" if c else "--"
        draft_rows.append(f"{system} & {pdraft} & {p['not_shown']} & {cdraft} " + r"\\")
    tex_table("t-audit.tex", "lccc", r"System & Page support & Unshown & Citation ($n$)", audit_rows,
              "Current AI population labels $\\to$ author-accepted answers on the same reviewed items, "
              "shown as counts rather than corrected population rates or independent human agreement. "
              "Page-support cells have 20 assigned assertions each; Unshown remains unresolved. "
              "Citation cells use only current in-frame items (sample size in parentheses); one B2 "
              "frame-error item accepted as supported is excluded from both sides. B5 is the reported build. "
              "Eight predecessor-build assertion items are omitted. "
              "Its accepted statement support is 18/20, but only 15/20 also satisfy pair-page participation. "
              "Sample labels are not spliced into the remaining population; system rankings are not inferred.",
              "tab:accepted-review")
    tex_table("t-audit-draft.tex", "lccc", r"System & Assertion yes & Unshown & Citation yes", draft_rows,
              "Frozen earlier-draft $\\to$ accepted counts of full-support labels. Every populated cell has "
              "20 assigned items, including unresolved assertion items and earlier uncertain/frame-error "
              "labels. Assertion counts use the historical statement question; the current page-context "
              "and citation labels differ in some items (Table~\\ref{tab:accepted-review}). "
              "These draft counts document review provenance, not current population quality.",
              "tab:frozen-draft-review")

    gold_rows = []
    for system in SYSTEMS:
        all_gold = cells["original"][system]["M1"]
        subset = sensitivity["original"][system]
        gold_rows.append(f"{system} & {all_gold['mean_over_cutoffs']:.3f} & "
                         f"{subset['mean_over_cutoffs']:.3f} & {subset['pooled']['num']}/{subset['pooled']['den']} " + r"\\")
    tex_table("t-gold-sensitivity.tex", "lccc", "System & All gold & Full packet & Subset count", gold_rows,
              "Original-text recall sensitivity to gold evidence support. All gold uses all 111 facts; "
              "Full packet retains the 85 whose displayed evidence packets were accepted as fully establishing "
              "the proposition. Means average five cutoffs; Subset count pools repeated fact-by-cutoff "
              "assessments. This post-hoc selection retains original reveal-volume labels, may select easier "
              "facts, and is not a repaired or independently validated benchmark.", "tab:gold-sensitivity")

    surface_rows = []
    for system, kind, label in (("B1", "cast", "Long context, cast"), ("B2", "cast", "Retrieval, cast"),
                                ("B4", "cast", "Graph retrieval, cast"), ("B5", "cast", "NarrativeWiki, cast"),
                                ("B5", "relationship", "NarrativeWiki, pairs"), ("B5", "all", "NarrativeWiki, all")):
        c = surfaces[system][kind]
        cite = f"{c['citation_sufficient']}/{c['citation_labelled']}" if c["citation_labelled"] else "--"
        surface_rows.append(f"{label} & {c['n']} & {c['statement_supported']} & {c['page_supported']} & {cite} " + r"\\")
    tex_table("t-surfaces.tex", "lrrrr", "Output stratum & $n$ & True & Page & Cites", surface_rows,
              "Stored AI precision samples on the original text, pooled over cutoffs. True counts statements "
              "supported by eligible text; Page additionally requires appropriate page placement (for pairs, "
              "both characters share an episode). Cites counts assertions established by their own cited "
              "paragraphs among atoms with a citation label (B4 has citation labels only at cutoff 1). "
              "Cast restricts to the evaluated character roster through each system's page map, "
              "but does not match assertion content. NarrativeWiki's 35 cast atoms cannot establish equivalence "
              "with the larger baseline samples. These are original AI labels, not accepted-review corrections.",
              "tab:surface-samples", wide=True)

    paired_rows = []
    for condition in ("original", "treated"):
        for system in ("B1", "B2", "B4", "X1"):
            p = paired[condition][system]
            paired_rows.append(f"{condition.title()} & {system} & {p['nw_only']} & {p['comparator_only']} & "
                               f"${p['mean_difference_over_cutoffs']:+.3f}$ " + r"\\")
    tex_table("t-paired.tex", "llrrr", "Condition & Other & NW only & Other only & Mean $\\Delta$", paired_rows,
              "Descriptive paired recall: NarrativeWiki minus each comparator over the identical "
              "335 eligible fact-by-cutoff assessments. NW only and Other only are discordant counts pooled "
              "over the five cutoffs; Mean $\\Delta$ averages cutoff-specific recall differences. "
              "Missing pages remain in the inventory. These are neither shared-output-page comparisons nor "
              "independent draws; no significance or causal memory contribution is inferred.",
              "tab:paired-assessments", wide=True)

    b4_rows = []
    for condition in ("original", "treated"):
        for system in ("B4", "B5"):
            c = cells[condition][system]
            disclosure = c["M4"]["pooled"]
            b4_rows.append(f"{condition.title()} & {system} & {c['M1']['mean_over_cutoffs']:.3f} & "
                           f"{c['M3']['mean_over_cutoffs']:.3f} & {disclosure['num']}/{disclosure['den']} " + r"\\")
    tex_table("t-b4.tex", "llrrr", "Condition & Output & Recall & Precision & Detected", b4_rows,
              "Same-graph diagnostic. B4 retrieves a budgeted graph subset and writes cast character pages; "
              "B5 renders the graph with additional pair, codex and timeline surfaces. Recall and precision "
              "are original AI-label means over five cutoffs; Detected counts stated/implied future-gold "
              "disclosures over 220 fact-by-cutoff probes. This controls the input graph, but changes retrieval, "
              "writer and output scope together; it does not isolate one architectural component. "
              "Search sensitivity is incomplete, so zeros are detection outcomes, not safety guarantees.",
              "tab:same-graph")

    readme = f"""# Deterministic reanalysis for the Codex paper

Run ID: `{runid}`.

Reproduce from the repository root:

```powershell
.venv/Scripts/python.exe -X utf8 scripts/papers/codex_paper_analysis.py
```

The script reads stored labels only, hashes every input in `reanalysis.json`, and never calls a model or writes old label files. Means use unrounded counts and are unweighted means across cutoff ratios. Pooled counts are a different estimand. Five views of one story are dependent.

## Accepted review

`human_check/final_labels.csv` is joined to the frozen item key. The authors reviewed and accepted AI answers; this is not independent human annotation. The user reports that author reviewers had general book knowledge, spent one day, and were unpaid; that metadata is user-supplied and is not inferable from the labels. Original/accepted `yes` counts, all categorical transitions, unresolved items, and pair participation are retained separately by system. B5 review items name `anne@v2`, the reported build; P2/P3 are obsolete-build diagnostics and do not enter the main audit table. The table uses count labels rather than turning uncertain or frame-error drafts into validated population outcomes. Citation-sufficiency draft errors can cancel in aggregate counts. Current source-label support and citation counts on the same review items are also recorded in the JSON, separately from frozen draft-agreement counts. Recall agreement after the population-wide six-fact re-read is a separate field from agreement with the older draft labels.

The P question assesses the factual statement; a separate pair question assesses placement. Accepted B5 statement support is 18/20, while statement support plus pair participation is 15/20. The main population precision uses the original scene sidecar; no review sample is silently spliced into the population. 'Not shown' remains unresolved, not false. Treated labels were not in this review.

## Evidence-packet sensitivity

All 111 gold facts received accepted evidence-packet answers: 85 yes, 23 partly, 3 no. The subset selects the 85 yes facts after review and recomputes every existing recall label on the corresponding eligible assessments. It does not repair pointers, re-date reveals, reassess the novel, or create new recall judgements. It retains original reveal-volume labels and may preferentially select easier facts. Treated-text selection is inherited from the original-text packets, so it does not establish treatment fidelity. Only the original-text sensitivity table is printed by default; treated results are in the JSON.

## Surface and paired analyses

`precision/pair_strict_claude.json` and `timeline_cite_claude.json` are applied exactly as the existing observation computation does. Sample page-support sums are checked against the official observation counts. Cast pages follow the original gold-character page map, matching the registry's `derived_values.py` definition, rather than guessing from page titles. The cast restriction matches page scope, not assertion content, and B5 has only 35 sampled cast atoms.

Paired recall requires identical gold-fact/cutoff keys for both systems and retains assessments with missing output pages. The original and treated sets each contain 335 repeated fact-by-cutoff units. Discordant counts are descriptive; means average cutoff-specific differences, not the pooled difference. B4 shares B5's graph but simultaneously changes selection, generation and output surfaces. Its comparison cannot identify the effect of one component or establish spoiler safety.

## Generated tables

- `tables/t-audit.tex`: current population-label versus accepted page-support/citation counts on identical review items, with unresolved assertions and citation frame exclusions explicit.
- `tables/t-audit-draft.tex`: historical earlier-draft label counts, whose exact categorical agreement is retained separately.
- `tables/t-gold-sensitivity.tex`: original-text, post-hoc fully-established evidence-packet subset.
- `tables/t-surfaces.tex`: cast/pair/whole-artifact original AI samples and explicit denominators.
- `tables/t-paired.tex`: exact common-assessment discordances and cutoff-mean differences.
- `tables/t-b4.tex`: same-graph original/treated diagnostic with bounded interpretation.

No independently blinded human evaluation, held-out corpus result, or new judgement was produced.
"""
    (OUT / "analysis" / "README.md").write_text(readme, encoding="utf-8", newline="\n")
    command = "`.venv/Scripts/python.exe -X utf8 scripts/papers/codex_paper_analysis.py`"
    ledger = ["## 2026-10-09 — Deterministic Codex-paper reanalysis", "",
              "| Date | Observation | Value / finding | Exact command or source | Run id / limits |",
              "|---|---|---|---|---|",]
    def ledger_row(label, value, limits):
        ledger.append(f"| 2026-10-09 | {label} | {value} | {command} | `{runid}`; {limits} |")
    ledger_row("Reanalysis source provenance", f"{len(INPUTS)} input files individually SHA-256 hashed in `paper_codex/analysis/reanalysis.json`",
               "stored labels only; no API, no output regeneration or source-label edits")
    for condition in ("original", "treated"):
        for system in SYSTEMS:
            c = sensitivity[condition][system]
            sequence = ", ".join(f"{x['num']}/{x['den']}" for x in c["cells"])
            ledger_row(f"Fully-established evidence-packet recall sensitivity, {condition}, {system}",
                       f"Cutoffs 1–5: {sequence}; mean {c['mean_over_cutoffs']:.6f}; pooled {c['pooled']['num']}/{c['pooled']['den']}",
                       "post-hoc 85/111 original evidence packets; original reveal labels retained; repeated facts; treated selection does not validate treatment fidelity")
        for system, p in paired[condition].items():
            ledger_row(f"Common-assessment recall pairing, {condition}, B5 minus {system}",
                       f"{p['den']} fact/cutoff assessments: both yes {p['both']}, neither {p['neither']}, B5 only {p['nw_only']}, other only {p['comparator_only']}; mean cutoff difference {p['mean_difference_over_cutoffs']:+.6f}",
                       "common gold assessments including missing pages; not shared output pages; no independence, significance or causal claim")
    for system, p in review["P"].items():
        ledger_row(f"Accepted author-review assertions, {system}",
                   f"n={p['n']}; current source statement/page support {p['current_statement_supported_count']}/{p['current_page_supported_count']}; accepted full statement/page support {p['accepted_labels'].get('yes', 0)}/{p['accepted_page_supported']}; unresolved not shown {p['not_shown']}; earlier categorical draft agreement {p['exact_draft_agreement']}/{p['n']}",
                   "AI answers accepted by authors; no population corrections; historical draft agreement differs from current-source labels; P2/P3 excluded from current-system main table")
    for system, c in review["C"].items():
        eligible = [x for x in c["current_item_labels"] if x["current_population_eligible"]]
